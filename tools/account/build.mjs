#!/usr/bin/env node
// Builds the account pages for one explicit mode. The mode is chosen here, at build time,
// never by query string, storage or user input on the page.
//
//   node tools/account/build.mjs --mode disabled
//       In place: the committed state. Pages say the account opens soon; no requests.
//   node tools/account/build.mjs --mode mock --out .preview/mock
//       Copy of the site with the in-memory demo server and its panel. Local testing only.
//   node tools/account/build.mjs --mode real --api-origin https://api-test.tikteam.live --out .preview/web-test
//       Copy of the site talking to that API origin. No demo code is included.

import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, isAbsolute, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const SITE = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
const ACCOUNT_JS = join("assets", "js", "account");
const ACCOUNT_PAGES = ["account/index.html", "account/recovery/index.html", "en/account/index.html", "en/account/recovery/index.html"];
const SKIP = new Set([".git", ".preview", "tools", "node_modules"]);
const WEB_PREFIX = "/api/web/v1";

function fail(message) { console.error("build-account: " + message); process.exit(1); }

function args(argv) {
  const out = {};
  for (let i = 0; i < argv.length; i++) {
    const name = argv[i];
    if (!/^--(mode|api-origin|checkout-origin|out)$/.test(name) || i + 1 >= argv.length) fail("unknown or incomplete argument: " + name);
    out[name.slice(2)] = argv[++i];
  }
  return out;
}

/** An exact https origin: no path, query, fragment, user info or explicit port. */
export function exactOrigin(value, label) {
  let url;
  try { url = new URL(value); } catch { fail(`${label} is not a URL`); }
  if (url.protocol !== "https:" || url.username || url.password || url.port || url.search || url.hash
    || (url.pathname !== "/" && url.pathname !== "") || !/^[a-z0-9.-]+$/.test(url.hostname) || value.replace(/\/$/, "") !== url.origin)
    fail(`${label} must be an exact https origin such as https://api.tikteam.live`);
  return url.origin;
}

export function configSource(mode, apiOrigin = "", checkoutOrigin = "") {
  const header = "// Generated by tools/account/build.mjs — do not edit by hand.\n";
  if (mode === "disabled") return header +
    "// Mode \"disabled\": the account pages say the account area opens soon and make no requests.\n" +
    "export const MODE = \"disabled\";\nexport const API_ORIGIN = \"\";\nexport const API_BASE = \"\";\nexport const CHECKOUT_ORIGIN = \"\";\n" +
    "export function createTransport() { return null; }\n";
  if (mode === "real") return header +
    "// Mode \"real\": the browser talks to this API origin with its own cookie and CSRF token.\n" +
    "export const MODE = \"real\";\n" +
    `export const API_ORIGIN = ${JSON.stringify(apiOrigin)};\n` +
    `export const API_BASE = ${JSON.stringify(apiOrigin + WEB_PREFIX)};\n` +
    `export const CHECKOUT_ORIGIN = ${JSON.stringify(checkoutOrigin)};\n` +
    "export function createTransport() { return (url, init) => fetch(url, init); }\n";
  if (mode === "mock") return header +
    "// Mode \"mock\": in-memory demo server, no network. Local testing only, never published.\n" +
    "import { mockServer, MOCK_API_BASE, MOCK_API_ORIGIN } from \"./mock-server.js\";\n" +
    "import \"./mock-panel.js\";\n" +
    "export const MODE = \"mock\";\nexport const API_ORIGIN = MOCK_API_ORIGIN;\nexport const API_BASE = MOCK_API_BASE;\nexport const CHECKOUT_ORIGIN = MOCK_API_ORIGIN;\n" +
    "export function createTransport() { return mockServer.transport; }\n";
  fail("mode must be disabled, mock or real");
}

/** Rewrites the CSP connect-src of the account pages for the chosen mode. */
function setConnectSource(root, source) {
  for (const page of ACCOUNT_PAGES) {
    const file = join(root, page);
    const html = readFileSync(file, "utf8");
    const matches = html.match(/connect-src [^;"]+/g) ?? [];
    if (matches.length !== 1) fail(`${page}: expected exactly one connect-src in its CSP`);
    writeFileSync(file, html.replace(/connect-src [^;"]+/, "connect-src " + source));
  }
}

function copySite(out) {
  // Inside the site only .preview/ is allowed: it is skipped when copying and ignored by git.
  const rel = relative(SITE, out);
  const inside = rel === "" || (!rel.startsWith("..") && !isAbsolute(rel));
  if (rel === "" || inside && rel.split(sep)[0] !== ".preview") fail("--out must be under .preview/ or outside the site");
  rmSync(out, { recursive: true, force: true });
  mkdirSync(out, { recursive: true });
  // Entry by entry: the output may sit inside the site (.preview/), which is itself skipped.
  for (const entry of readdirSync(SITE)) {
    if (SKIP.has(entry)) continue;
    cpSync(join(SITE, entry), join(out, entry), { recursive: true });
  }
}

export function build({ mode, apiOrigin, checkoutOrigin, out }) {
  if (!["disabled", "mock", "real"].includes(mode)) fail("--mode must be disabled, mock or real");
  if (mode === "real" && !apiOrigin) fail("--mode real needs --api-origin");
  if (mode !== "real" && (apiOrigin || checkoutOrigin)) fail("--api-origin is only for --mode real");
  if (mode === "mock" && !out) fail("--mode mock needs --out: demo code is never written into the site itself");
  const api = mode === "real" ? exactOrigin(apiOrigin, "--api-origin") : "";
  const checkout = mode === "real" ? exactOrigin(checkoutOrigin ?? api, "--checkout-origin") : "";

  const root = out ? resolve(out) : SITE;
  if (out) copySite(root);
  const jsDir = join(root, ACCOUNT_JS);
  writeFileSync(join(jsDir, "config.js"), configSource(mode, api, checkout));
  // Mock never touches the network; real builds may only reach their own API origin.
  setConnectSource(root, mode === "real" ? api : "'none'");
  for (const file of ["mock-server.js", "mock-panel.js", "mock-panel.css"]) {
    const target = join(jsDir, file);
    if (mode === "mock") cpSync(join(SITE, "tools", "account", "mock", file), target);
    else if (existsSync(target)) rmSync(target);
  }
  return { mode, root, api, checkout };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const a = args(process.argv.slice(2));
  const result = build({ mode: a.mode, apiOrigin: a["api-origin"], checkoutOrigin: a["checkout-origin"], out: a.out });
  console.log(`account pages built: mode=${result.mode}${result.api ? " api=" + result.api : ""} → ${relative(process.cwd(), result.root) || "."}`);
}
